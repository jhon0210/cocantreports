-- Extensión del esquema para Caracterizar, reportes con trazabilidad y refresh tokens.
-- Cambios aditivos: no se elimina ni renombra nada del modelo original.

-- 1) ECAs: ruta y macroruta
ALTER TABLE "ecas"
  ADD COLUMN IF NOT EXISTS "ruta" VARCHAR,
  ADD COLUMN IF NOT EXISTS "macroruta" VARCHAR;

-- 2) Usuarios: baja lógica (los reportes históricos conservan su autor)
ALTER TABLE "usuarios"
  ADD COLUMN IF NOT EXISTS "activo" BOOLEAN NOT NULL DEFAULT true;

-- 3) Claves naturales únicas necesarias para login, selects y seeders idempotentes
CREATE UNIQUE INDEX IF NOT EXISTS "usuarios_usuario_key" ON "usuarios" ("usuario");
CREATE UNIQUE INDEX IF NOT EXISTS "roles_perfil_key" ON "roles" ("perfil");
CREATE UNIQUE INDEX IF NOT EXISTS "materiales_codigo_key" ON "materiales" ("codigo");

-- 4) Recuperadores (nueva tabla). La cédula es VARCHAR para no desbordar INT (cédulas de 10 dígitos)
--    ni perder ceros a la izquierda.
CREATE TABLE IF NOT EXISTS "recuperadores" (
  "id_recuperador" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "nombre" VARCHAR(100) NOT NULL,
  "apellido" VARCHAR(100) NOT NULL,
  "cedula" VARCHAR(15) NOT NULL,
  "id_eca" INT NOT NULL,
  "bancarizado" BOOLEAN NOT NULL DEFAULT false,
  "foto" TEXT,
  "FechaRegistro" DATE NOT NULL DEFAULT CURRENT_DATE,
  CONSTRAINT "recuperadores_cedula_formato_chk" CHECK ("cedula" ~ '^[0-9]{5,15}$'),
  CONSTRAINT "recuperadores_id_eca_fkey" FOREIGN KEY ("id_eca") REFERENCES "ecas" ("id_eca") ON DELETE NO ACTION ON UPDATE NO ACTION
);
CREATE UNIQUE INDEX IF NOT EXISTS "recuperadores_cedula_key" ON "recuperadores" ("cedula");
CREATE INDEX IF NOT EXISTS "recuperadores_id_eca_idx" ON "recuperadores" ("id_eca");

-- 5) Refresh tokens con rotación y detección de reutilización (se guarda solo el hash SHA-256)
CREATE TABLE IF NOT EXISTS "refresh_tokens" (
  "id" UUID PRIMARY KEY,
  "familia" UUID NOT NULL,
  "id_user" INT NOT NULL,
  "token_hash" VARCHAR(64) NOT NULL,
  "expires_at" TIMESTAMPTZ(6) NOT NULL,
  "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
  "revoked_at" TIMESTAMPTZ(6),
  "replaced_by" UUID,
  CONSTRAINT "refresh_tokens_id_user_fkey" FOREIGN KEY ("id_user") REFERENCES "usuarios" ("id_user") ON DELETE CASCADE ON UPDATE NO ACTION
);
CREATE INDEX IF NOT EXISTS "refresh_tokens_id_user_idx" ON "refresh_tokens" ("id_user");
CREATE INDEX IF NOT EXISTS "refresh_tokens_familia_idx" ON "refresh_tokens" ("familia");

-- 6) matReportado: clave primaria real, relación con el recuperador y columnas obligatorias
DO $$
DECLARE
  hay_problemas BOOLEAN;
  siguiente BIGINT;
BEGIN
  -- Si hay consecutivos nulos o repetidos (la tabla original no tenía PK), se renumeran.
  SELECT COUNT(*) <> COUNT("consecutivo") OR COUNT("consecutivo") <> COUNT(DISTINCT "consecutivo")
    INTO hay_problemas FROM "matReportado";
  IF hay_problemas THEN
    WITH numeradas AS (
      SELECT ctid AS fila, ROW_NUMBER() OVER (ORDER BY "consecutivo" NULLS LAST, ctid) AS n
      FROM "matReportado"
    )
    UPDATE "matReportado" m SET "consecutivo" = numeradas.n
    FROM numeradas WHERE m.ctid = numeradas.fila;
  END IF;

  UPDATE "matReportado" SET "FechaVenta" = COALESCE("FechaVenta", "FechaRegistro", CURRENT_DATE) WHERE "FechaVenta" IS NULL;
  UPDATE "matReportado" SET "FechaRegistro" = COALESCE("FechaRegistro", "FechaVenta", CURRENT_DATE) WHERE "FechaRegistro" IS NULL;

  ALTER TABLE "matReportado"
    ALTER COLUMN "consecutivo" SET NOT NULL,
    ALTER COLUMN "id_mat" SET NOT NULL,
    ALTER COLUMN "cantidad" SET NOT NULL,
    ALTER COLUMN "valor" SET NOT NULL,
    ALTER COLUMN "id_user" SET NOT NULL,
    ALTER COLUMN "id_eca" SET NOT NULL,
    ALTER COLUMN "FechaRegistro" SET NOT NULL,
    ALTER COLUMN "FechaRegistro" SET DEFAULT CURRENT_DATE,
    ALTER COLUMN "FechaVenta" SET NOT NULL,
    ALTER COLUMN "FechaVenta" SET DEFAULT CURRENT_DATE;

  ALTER TABLE "matReportado" ALTER COLUMN "consecutivo" ADD GENERATED BY DEFAULT AS IDENTITY;
  SELECT COALESCE(MAX("consecutivo"), 0) + 1 INTO siguiente FROM "matReportado";
  EXECUTE format('ALTER TABLE "matReportado" ALTER COLUMN "consecutivo" RESTART WITH %s', siguiente);

  ALTER TABLE "matReportado" ADD CONSTRAINT "matReportado_pkey" PRIMARY KEY ("consecutivo");
END $$;

-- Relación inequívoca reporte -> recuperador (nullable para no invalidar reportes históricos)
ALTER TABLE "matReportado" ADD COLUMN IF NOT EXISTS "id_recuperador" INT;
ALTER TABLE "matReportado"
  ADD CONSTRAINT "matReportado_id_recuperador_fkey"
  FOREIGN KEY ("id_recuperador") REFERENCES "recuperadores" ("id_recuperador") ON DELETE NO ACTION ON UPDATE NO ACTION;

-- Valores positivos (NOT VALID: se exigen en inserciones nuevas sin bloquear datos históricos)
ALTER TABLE "matReportado" ADD CONSTRAINT "matReportado_cantidad_positiva_chk" CHECK ("cantidad" > 0) NOT VALID;
ALTER TABLE "matReportado" ADD CONSTRAINT "matReportado_valor_positivo_chk" CHECK ("valor" > 0) NOT VALID;

CREATE INDEX IF NOT EXISTS "matReportado_id_user_idx" ON "matReportado" ("id_user");
CREATE INDEX IF NOT EXISTS "matReportado_id_recuperador_idx" ON "matReportado" ("id_recuperador");
CREATE INDEX IF NOT EXISTS "matReportado_FechaVenta_idx" ON "matReportado" ("FechaVenta");
